const longest = Math.max(2, ...Object.keys(phrases).map((source) => [...source].length));
const cache = new Map<string, string>();
export function toTraditional(text: string): string {
  if (!text) return text;
  const cached = cache.get(text);
  if (cached !== undefined) return cached;
  let output = '';
  for (let index = 0; index < text.length; ) {
    const character = String.fromCodePoint(text.codePointAt(index)!);
    if (!/\p{Script=Han}/u.test(character)) {
      output += character;
      index += character.length;
      continue;
    }
    let matched = false;
    for (let length = Math.min(longest, text.length - index); length >= 2; length--) {
      const source = text.slice(index, index + length);
      const target = phrases[source];
      if (target) {
        output += target;
        index += length;
        matched = true;
        break;
      }
    }
    if (!matched) {
      output += characters[character] || character;
      index += character.length;
    }
  }
  for (const [source, target] of replacements) output = output.split(source).join(target);
  cache.set(text, output);
  return output;
}
